const catalogs: Record<Locale, Record<MessageKey, string>> = { "zh-CN": zhCN, en };
const LocaleContext = createContext<Locale>("zh-CN");

export function LocaleProvider({ initialLocale, children }: { initialLocale: string; children: React.ReactNode }) {
  const locale: Locale = initialLocale === "en" ? "en" : "zh-CN";
  return <LocaleContext.Provider value={locale}>{children}</LocaleContext.Provider>;
}

export function useI18n() {
  const locale = useContext(LocaleContext);
  return useMemo(() => ({
    locale,
    t(key: MessageKey, values: Record<string, string | number> = {}) {
      return Object.entries(values).reduce((message, [name, value]) => message.replaceAll(`{${name}}`, String(value)), catalogs[locale][key]);
    },
  }), [locale]);
}
